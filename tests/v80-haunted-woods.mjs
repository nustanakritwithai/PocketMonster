import assert from 'node:assert/strict';
import { STAGE_BY_ID, createStageProgress, recordStageClear, stageUnlockReason, stageRewards } from '../stage-catalog.mjs';
import { routesFrom, warpAvailability } from '../warp-routes.mjs';
import { activeJs as js } from './active-assets.mjs';

const stage=STAGE_BY_ID['haunted-woods'];
assert.ok(stage,'Haunted Woods catalog definition exists');
assert.deepEqual(stage.primaryTypes,['Ghost'],'Haunted Woods is Ghost-led');
assert.deepEqual(stage.secondaryTypes,['Dark','Poison'],'Haunted Woods supports Dark and Poison');
assert.deepEqual(stage.recommendedLevel,{min:22,max:26},'Haunted Woods level range is stable');
assert.equal(stage.capturePolicy,'normal-wild-only','Haunted Woods keeps Boss capture disabled policy');
assert.ok(Object.keys(stageRewards('haunted-woods')).length>0,'Haunted Woods has catalog-owned rewards');
assert.equal(routesFrom('dream-shrine').some(route=>route.to==='haunted-woods'),true,'Dream Shrine has Haunted Woods forward warp');
assert.equal(routesFrom('haunted-woods').some(route=>route.to==='dream-shrine'),true,'Haunted Woods has safe return warp');
const progress=createStageProgress();
for(const id of ['frozen-pass','rocky-canyon','sky-ruins','poison-marsh','dream-shrine'])Object.assign(progress,recordStageClear(progress,id));
assert.equal(stageUnlockReason(progress,'haunted-woods').ok,true,'Dream Shrine clear unlocks Haunted Woods');
const route=routesFrom('dream-shrine').find(candidate=>candidate.to==='haunted-woods');
assert.equal(warpAvailability(progress,route,stageUnlockReason).ok,true,'Haunted Woods route is available after Dream Shrine');
const zoneBlock=js.match(/['"]haunted-woods['"]\s*:\s*\{[\s\S]*?(?=\n  ['"]shadow-city['"]\s*:)/)?.[0]||'';
assert.match(zoneBlock,/stageId:'haunted-woods'/,'Haunted Woods runtime zone is catalog-linked');
assert.match(zoneBlock,/spawn:\[/,'Haunted Woods has Normal encounter spawn data');
assert.match(zoneBlock,/eliteSpawn:\[/,'Haunted Woods has Elite encounter data');
assert.match(zoneBlock,/bossSpawn:\[/,'Haunted Woods has Boss encounter data');
assert.match(zoneBlock,/progressionBossSpeciesId:/,'Haunted Woods has deterministic Boss progression');
assert.match(zoneBlock,/sceneStatus:'stage-ready'/,'Haunted Woods is presentation-only');
assert.match(js,/zone==='haunted-woods'\?'woods'/,'Haunted Woods uses its own ground presentation');
assert.doesNotMatch(zoneBlock,/playerData\.hp|status|damage|teleport|fly|jump|fear/,'Haunted Woods has no fear/status or terrain logic');
console.log('V8 Haunted Woods: PASS');
