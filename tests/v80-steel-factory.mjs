import assert from 'node:assert/strict';
import { STAGE_BY_ID, createStageProgress, recordStageClear, stageUnlockReason, stageRewards } from '../stage-catalog.mjs';
import { routesFrom, warpAvailability } from '../warp-routes.mjs';
import { activeJs as js } from './active-assets.mjs';

const stage=STAGE_BY_ID['steel-factory'];
assert.ok(stage,'Steel Factory catalog definition exists');
assert.deepEqual(stage.primaryTypes,['Steel'],'Steel Factory is Steel-led');
assert.deepEqual(stage.secondaryTypes,['Electric','Rock'],'Steel Factory supports Electric and Rock');
assert.deepEqual(stage.recommendedLevel,{min:26,max:30},'Steel Factory level range is stable');
assert.equal(stage.capturePolicy,'normal-wild-only','Steel Factory keeps Boss capture disabled policy');
assert.ok(Object.keys(stageRewards('steel-factory')).length>0,'Steel Factory has catalog-owned rewards');
assert.equal(routesFrom('shadow-city').some(route=>route.to==='steel-factory'),true,'Shadow City has Steel Factory forward warp');
assert.equal(routesFrom('steel-factory').some(route=>route.to==='shadow-city'),true,'Steel Factory has safe return warp');
const progress=createStageProgress();
for(const id of ['frozen-pass','rocky-canyon','sky-ruins','poison-marsh','dream-shrine','haunted-woods','shadow-city'])Object.assign(progress,recordStageClear(progress,id));
assert.equal(stageUnlockReason(progress,'steel-factory').ok,true,'Shadow City clear unlocks Steel Factory');
const route=routesFrom('shadow-city').find(candidate=>candidate.to==='steel-factory');
assert.equal(warpAvailability(progress,route,stageUnlockReason).ok,true,'Steel Factory route is available after Shadow City');
const zoneBlock=js.match(/['"]steel-factory['"]\s*:\s*\{[\s\S]*?(?=\n  ['"][^'"]+['"]\s*:\s*\{)/)?.[0]||'';
assert.match(zoneBlock,/stageId:'steel-factory'/,'Steel Factory runtime zone is catalog-linked');
assert.match(zoneBlock,/spawn:\[/,'Steel Factory has Normal encounter spawn data');
assert.match(zoneBlock,/eliteSpawn:\[/,'Steel Factory has Elite encounter data');
assert.match(zoneBlock,/bossSpawn:\[/,'Steel Factory has Boss encounter data');
assert.match(zoneBlock,/progressionBossSpeciesId:/,'Steel Factory has deterministic Boss progression');
assert.match(zoneBlock,/sceneStatus:'stage-ready'/,'Steel Factory is presentation-only');
assert.match(js,/zone==='steel-factory'\?'factory'/,'Steel Factory uses its own ground presentation');
assert.doesNotMatch(zoneBlock,/playerData\.hp|status|damage|teleport|fly|jump|conveyor|contact/,'Steel Factory has no hazard physics or damage logic');
console.log('V8 Steel Factory: PASS');
