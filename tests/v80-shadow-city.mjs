import assert from 'node:assert/strict';
import { STAGE_BY_ID, createStageProgress, recordStageClear, stageUnlockReason, stageRewards } from '../stage-catalog.mjs';
import { routesFrom, warpAvailability } from '../warp-routes.mjs';
import { activeJs as js } from './active-assets.mjs';

const stage=STAGE_BY_ID['shadow-city'];
assert.ok(stage,'Shadow City catalog definition exists');
assert.deepEqual(stage.primaryTypes,['Dark'],'Shadow City is Dark-led');
assert.deepEqual(stage.secondaryTypes,['Poison','Fighting'],'Shadow City supports Poison and Fighting');
assert.deepEqual(stage.recommendedLevel,{min:24,max:28},'Shadow City level range is stable');
assert.equal(stage.capturePolicy,'normal-wild-only','Shadow City keeps Boss capture disabled policy');
assert.ok(Object.keys(stageRewards('shadow-city')).length>0,'Shadow City has catalog-owned rewards');
assert.equal(routesFrom('haunted-woods').some(route=>route.to==='shadow-city'),true,'Haunted Woods has Shadow City forward warp');
assert.equal(routesFrom('shadow-city').some(route=>route.to==='haunted-woods'),true,'Shadow City has safe return warp');
const progress=createStageProgress();
for(const id of ['frozen-pass','rocky-canyon','sky-ruins','poison-marsh','dream-shrine','haunted-woods'])Object.assign(progress,recordStageClear(progress,id));
assert.equal(stageUnlockReason(progress,'shadow-city').ok,true,'Haunted Woods clear unlocks Shadow City');
const route=routesFrom('haunted-woods').find(candidate=>candidate.to==='shadow-city');
assert.equal(warpAvailability(progress,route,stageUnlockReason).ok,true,'Shadow City route is available after Haunted Woods');
const zoneBlock=js.match(/['"]shadow-city['"]\s*:\s*\{[\s\S]*?(?=\n  ['"]sky-ruins['"]\s*:)/)?.[0]||'';
assert.match(zoneBlock,/stageId:'shadow-city'/,'Shadow City runtime zone is catalog-linked');
assert.match(zoneBlock,/spawn:\[/,'Shadow City has Normal encounter spawn data');
assert.match(zoneBlock,/eliteSpawn:\[/,'Shadow City has Elite encounter data');
assert.match(zoneBlock,/bossSpawn:\[/,'Shadow City has Boss encounter data');
assert.match(zoneBlock,/progressionBossSpeciesId:/,'Shadow City has deterministic Boss progression');
assert.match(zoneBlock,/sceneStatus:'stage-ready'/,'Shadow City is presentation-only');
assert.match(js,/zone==='shadow-city'\?'city'/,'Shadow City uses its own ground presentation');
assert.doesNotMatch(zoneBlock,/playerData\.hp|status|damage|teleport|fly|jump|blackout/,'Shadow City has no darkness gameplay logic');
console.log('V8 Shadow City: PASS');
