import assert from 'node:assert/strict';
import { STAGE_BY_ID, createStageProgress, recordStageClear, stageUnlockReason, stageRewards } from '../stage-catalog.mjs';
import { routesFrom, warpAvailability } from '../warp-routes.mjs';
import { activeJs as js } from './active-assets.mjs';

const stage=STAGE_BY_ID['dream-shrine'];
assert.ok(stage,'Dream Shrine catalog definition exists');
assert.deepEqual(stage.primaryTypes,['Psychic'],'Dream Shrine is Psychic-led');
assert.deepEqual(stage.secondaryTypes,['Fairy','Normal'],'Dream Shrine supports Fairy and Normal');
assert.deepEqual(stage.recommendedLevel,{min:20,max:24},'Dream Shrine level range is stable');
assert.equal(stage.capturePolicy,'normal-wild-only','Dream Shrine keeps Boss capture disabled policy');
assert.ok(Object.keys(stageRewards('dream-shrine')).length>0,'Dream Shrine has catalog-owned rewards');
assert.equal(routesFrom('poison-marsh').some(route=>route.to==='dream-shrine'),true,'Poison Marsh has Dream Shrine forward warp');
assert.equal(routesFrom('dream-shrine').some(route=>route.to==='poison-marsh'),true,'Dream Shrine has safe return warp');
const progress=createStageProgress();
for(const id of ['frozen-pass','rocky-canyon','sky-ruins','poison-marsh'])Object.assign(progress,recordStageClear(progress,id));
assert.equal(stageUnlockReason(progress,'dream-shrine').ok,true,'Set 2 clear unlocks Dream Shrine');
const route=routesFrom('poison-marsh').find(candidate=>candidate.to==='dream-shrine');
assert.equal(warpAvailability(progress,route,stageUnlockReason).ok,true,'Dream Shrine route is available after Set 2');
const zoneBlock=js.match(/['"]dream-shrine['"]\s*:\s*\{[\s\S]*?(?=\n  ['"]sky-ruins['"]\s*:)/)?.[0]||'';
assert.match(zoneBlock,/stageId:'dream-shrine'/,'Dream Shrine runtime zone is catalog-linked');
assert.match(zoneBlock,/spawn:\[/,'Dream Shrine has Normal encounter spawn data');
assert.match(zoneBlock,/eliteSpawn:\[/,'Dream Shrine has Elite encounter data');
assert.match(zoneBlock,/bossSpawn:\[/,'Dream Shrine has Boss encounter data');
assert.match(zoneBlock,/progressionBossSpeciesId:/,'Dream Shrine has deterministic Boss progression');
assert.match(zoneBlock,/sceneStatus:'stage-ready'/,'Dream Shrine is presentation-only');
assert.match(js,/zone==='dream-shrine'\?'shrine'/,'Dream Shrine uses its own ground presentation');
assert.doesNotMatch(zoneBlock,/playerData\.hp|status|damage|teleport|fly|jump/,'Dream Shrine has no confusion/control or terrain logic');
console.log('V8 Dream Shrine: PASS');
